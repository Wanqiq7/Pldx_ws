// Run with Node.js and jsdom installed: node test_xml.cjs
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { JSDOM } = require('jsdom');
const html = fs.readFileSync(path.join(__dirname, 'bt_editor.html'), 'utf8');
const dom = new JSDOM('', { runScripts: 'outside-only' });
dom.window.eval(html.match(/<script>\s*([\s\S]*?)<\/script>/)[1] + '\nwindow.BTXML = BTXML;');
const api = dom.window.BTXML;
let id = 0;
const graph = tree => api.graph(tree, [], () => String(++id));
const trees = file => Array.from(file.doc.documentElement.children).filter(el => el.tagName === 'BehaviorTree');
const nav = api.parse(fs.readFileSync(path.join(__dirname, '../../decision/bt_manager/tree/nav_tree.xml'), 'utf8'));
const navGraph = graph(trees(nav)[0]);
assert.equal(navGraph.nodes[0].data.label, 'MainReactiveSequence');
assert(!navGraph.nodes.some(n => ['root', 'include', 'BehaviorTree'].includes(n.type)));
api.writeTree(nav.doc, trees(nav)[0], navGraph);
assert.equal(nav.doc.querySelector('root > include').getAttribute('path'), 'recovery_tree.xml');
assert.equal(nav.doc.querySelectorAll('root').length, 1);
assert.equal(nav.doc.querySelectorAll('BehaviorTree').length, 1);

const file = api.parse(`<root BTCPP_format="4" main_tree_to_execute="Main"><include path="other.xml"/><!--keep--><BehaviorTree ID="Child" custom="keep"><AlwaysSuccess/></BehaviorTree><BehaviorTree ID="Main"><Sequence><SubTree ID="Child" _autoremap="true" value="{goal}"/><Say text="a &amp; &quot;b&quot;"/></Sequence></BehaviorTree><TreeNodesModel><Action ID="Say"><input_port name="text"/></Action></TreeNodesModel></root>`);
assert.equal(file.main, 'Main');
const originals = trees(file);
const childBefore = originals[0].outerHTML;
const mainGraph = graph(originals[1]);
assert.equal(mainGraph.nodes.filter(n => n.type === 'SubTree').length, 1);
mainGraph.nodes.find(n => n.type === 'Say').data.attributes.text = 'new < & " value';
// Assign layout order as the editor does.
mainGraph.nodes.forEach((n, index) => n.x = index * 100);
api.writeTree(file.doc, originals[1], mainGraph);
assert.equal(originals[0].outerHTML, childBefore);
const exported = new dom.window.XMLSerializer().serializeToString(file.doc);
const roundtrip = api.parse(exported);
assert.equal(roundtrip.doc.documentElement.getAttribute('BTCPP_format'), '4');
assert.equal(roundtrip.doc.querySelector('SubTree').getAttribute('_autoremap'), 'true');
assert.equal(roundtrip.doc.querySelector('Say').getAttribute('text'), 'new < & " value');
assert(roundtrip.doc.querySelector('TreeNodesModel input_port'));
assert(exported.includes('<!--keep-->'));
assert.throws(() => api.parse('<root>'), /XML/);
assert.throws(() => api.parse('<root><BehaviorTree ID="X"><A/><B/></BehaviorTree></root>'), /根节点/);
assert.throws(() => api.parse('<root main_tree_to_execute="Missing"><BehaviorTree ID="X"><A/></BehaviorTree></root>'), /主树/);
const invalid = graph(originals[0]);
invalid.nodes.push({ id: 'orphan', type: 'A', data: {} });
assert.throws(() => api.writeTree(file.doc, originals[0], invalid), /根节点/);
const cycle = graph(originals[1]);
cycle.edges.push({ source: cycle.nodes[1].id, target: cycle.nodes[0].id });
assert.throws(() => api.writeTree(file.doc, originals[1], cycle));
console.log('PASS: nav_tree import/export, multi-tree preservation, SubTree, metadata, escaping, invalid XML and graph rejection');
