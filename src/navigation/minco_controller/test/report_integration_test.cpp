TEST(ReportMpc, OneStepMatchesForceInputAnalyticSolution)
{
  ReportMpcConfig cfg;
  cfg.motion.horizon = 1;
  cfg.motion.dt = 0.2;
  cfg.motion.mass = 2.0;
  cfg.motion.inertia_z = 0.5;
  cfg.motion.max_force = 100.0;
  cfg.motion.max_torque = 100.0;
  cfg.motion.vx_min = cfg.motion.vy_min = cfg.motion.omega_min = -100.0;
  cfg.motion.vx_max = cfg.motion.vy_max = cfg.motion.omega_max = 100.0;
  cfg.q = {2, 3, 4, 5, 6, 7};
  cfg.r = {0.3, 0.4, 0.5};
  ReportMpcSolver solver(cfg);
  State current;
  current.x = 0.4;
  current.y = -0.1;
  current.yaw = 0.2;
  current.vx = 0.3;
  current.vy = -0.2;
  current.omega = 0.1;
  ReferencePoint reference;
  reference.pos = {1.0, 1.0};
  reference.yaw = -0.4;
  reference.vel = {0.8, -0.7};
  reference.yaw_rate = 0.5;
  DynamicControl control;
  std::vector<State> prediction;
  ASSERT_TRUE(solver.solve(current, {reference}, control, &prediction));
  ASSERT_EQ(prediction.size(), 2u);
  const Eigen::Vector3d v(current.vx, current.vy, current.omega);
  const Eigen::Vector3d ref(reference.vel.x(), reference.vel.y(), reference.yaw_rate);
  const Eigen::Vector3d b(
    cfg.motion.dt / cfg.motion.mass, cfg.motion.dt / cfg.motion.mass, cfg.motion.dt / cfg.motion.inertia_z);
  for (int j = 0; j < 3; ++j) {
    const double expected = cfg.q[j + 3] * b[j] * (ref[j] - v[j]) / (cfg.q[j + 3] * b[j] * b[j] + cfg.r[j]);
    EXPECT_NEAR(control.wrench[j], expected, 1e-8);
  }
  EXPECT_NEAR(prediction[1].x, current.x + cfg.motion.dt * current.vx, 1e-9);
  EXPECT_NEAR(prediction[1].y, current.y + cfg.motion.dt * current.vy, 1e-9);
  EXPECT_NEAR(prediction[1].yaw, current.yaw + cfg.motion.dt * current.omega, 1e-9);
  EXPECT_NEAR(prediction[1].vx, current.vx + b.x() * control.wrench.x(), 1e-9);
  EXPECT_NEAR(control.acceleration.x(), control.wrench.x() / cfg.motion.mass, 1e-9);
}

TEST(ReportMpc, BoundsFailureRecoveryAndCommit)
{
  ReportMpcConfig cfg;
  cfg.motion.horizon = 6;
  cfg.motion.dt = 0.2;
  cfg.motion.mass = 2.0;
  cfg.motion.inertia_z = 0.5;
  cfg.motion.max_force = 0.5;
  cfg.motion.max_torque = 0.25;
  cfg.motion.vx_min = cfg.motion.vy_min = cfg.motion.omega_min = -0.12;
  cfg.motion.vx_max = cfg.motion.vy_max = cfg.motion.omega_max = 0.12;
  cfg.q = {3, 3, 2, 20, 20, 10};
  cfg.r = {0.2, 0.2, 0.2};
  ReportMpcSolver solver(cfg);
  ReferencePoint ref;
  ref.vel = {9.0, -9.0};
  ref.yaw_rate = 9.0;
  std::vector<ReferencePoint> references(6, ref);
  DynamicControl control;
  std::vector<State> predicted;
  ASSERT_TRUE(solver.solve(State{}, references, control, &predicted, false));
  EXPECT_NEAR(control.wrench.x(), 0.5, 1e-7);
  EXPECT_NEAR(control.wrench.y(), -0.5, 1e-7);
  EXPECT_NEAR(control.wrench.z(), 0.25, 1e-7);
  EXPECT_NEAR(solver.getLastAcceleration().norm(), 0.0, 1e-12);
  for (const auto & p : predicted) {
    EXPECT_LE(std::abs(p.vx), 0.1200001);
    EXPECT_LE(std::abs(p.vy), 0.1200001);
    EXPECT_LE(std::abs(p.omega), 0.1200001);
  }
  ASSERT_TRUE(solver.solve(State{}, references, control, &predicted, true));
  EXPECT_GT(solver.getLastAcceleration().norm(), 0.1);
  solver.setAppliedWrench(Eigen::Vector3d(0.3, 0.4, 0.2));
  EXPECT_NEAR(solver.getLastAcceleration().x(), 0.15, 1e-12);
  EXPECT_NEAR(solver.getLastAcceleration().y(), 0.2, 1e-12);
  EXPECT_NEAR(solver.getLastAcceleration().z(), 0.4, 1e-12);
  State impossible;
  impossible.vx = 5.0;
  EXPECT_FALSE(solver.solve(impossible, references, control));
  ASSERT_TRUE(solver.solve(State{}, std::vector<ReferencePoint>(6), control));
  EXPECT_LT(control.wrench.norm(), 1e-7);
}

TEST(ReportMpc, FortyStepSolutionMatchesPythonDenseQp)
{
  ReportMpcConfig cfg;
  cfg.motion.horizon = 40;
  cfg.motion.dt = 0.02;
  cfg.motion.mass = 28.0;
  cfg.motion.inertia_z = 0.58;
  cfg.motion.max_force = 56.0;
  cfg.motion.max_torque = 2.32;
  cfg.motion.vx_min = cfg.motion.vy_min = -3.0;
  cfg.motion.vx_max = cfg.motion.vy_max = 3.0;
  cfg.motion.omega_min = -5.0;
  cfg.motion.omega_max = 5.0;
  ReportMpcSolver solver(cfg);
  State current;
  current.x = 0.1;
  current.y = -0.1;
  current.yaw = 0.1;
  std::vector<ReferencePoint> references(40);
  for (int k = 0; k < 40; ++k) {
    references[k].pos = {0.05 + 0.025 * k, -0.05 + 0.01 * k};
    references[k].yaw = 0.2 - 0.004 * k;
    references[k].vel = {0.7, 0.1};
    references[k].yaw_rate = -0.1;
  }
  DynamicControl control;
  std::vector<State> prediction;
  ASSERT_TRUE(solver.solve(current, references, control, &prediction));
  ASSERT_EQ(prediction.size(), 41u);

  // Fixture generated by omnidirectional_report_tracking.py with CasADi/qpOASES.
  const Eigen::Vector3d expected_first(56.0, 56.0, -0.08599772199713);
  const Eigen::Vector3d expected_tenth(56.0, 56.0, -0.10762290515092);
  const Eigen::Vector3d expected_last(-13.7472362717466, -6.80242906131086, -0.00232989370755122);
  const auto recovered_wrench = [&](size_t k) -> Eigen::Vector3d {
    return Eigen::Vector3d((prediction[k + 1].vx - prediction[k].vx) * cfg.motion.mass / cfg.motion.dt,
      (prediction[k + 1].vy - prediction[k].vy) * cfg.motion.mass / cfg.motion.dt,
      (prediction[k + 1].omega - prediction[k].omega) * cfg.motion.inertia_z / cfg.motion.dt);
  };
  EXPECT_LT((control.wrench - expected_first).norm(), 1e-4);
  EXPECT_LT((recovered_wrench(10) - expected_tenth).norm(), 1e-4);
  EXPECT_LT((recovered_wrench(39) - expected_last).norm(), 1e-4);
  const auto & last = prediction.back();
  EXPECT_NEAR(last.x, 0.64741723069278, 1e-6);
  EXPECT_NEAR(last.y, 0.16902957563194, 1e-6);
  EXPECT_NEAR(last.yaw, 0.05277797657005, 1e-6);
  EXPECT_NEAR(last.vx, 0.89246130780445, 1e-6);
  EXPECT_NEAR(last.vy, 0.19523400685835, 1e-6);
  EXPECT_NEAR(last.omega, -0.0932433082481, 1e-6);
}

TEST(ReportMpc, ReconfigurationUpdatesModelWeightsAndBounds)
{
  ReportMpcConfig cfg;
  cfg.motion.horizon = 1;
  cfg.motion.dt = 0.2;
  cfg.motion.mass = 2.0;
  cfg.motion.inertia_z = 1.0;
  cfg.motion.max_force = 100.0;
  cfg.motion.max_torque = 100.0;
  cfg.motion.vx_min = cfg.motion.vy_min = cfg.motion.omega_min = -10.0;
  cfg.motion.vx_max = cfg.motion.vy_max = cfg.motion.omega_max = 10.0;
  cfg.q = {0, 0, 0, 10, 0, 0};
  cfg.r = {1, 1, 1};
  ReportMpcSolver solver(cfg);
  ReferencePoint ref;
  ref.vel.x() = 2.0;
  DynamicControl control;
  ASSERT_TRUE(solver.solve(State{}, {ref}, control));
  EXPECT_NEAR(control.wrench.x(), 20.0 / 11.0, 1e-5);

  cfg.motion.mass = 4.0;
  cfg.motion.max_force = 0.25;
  cfg.q[3] = 20.0;
  solver.setConfig(cfg);
  ASSERT_TRUE(solver.solve(State{}, {ref}, control));
  EXPECT_NEAR(control.wrench.x(), 0.25, 1e-5);
  cfg.motion.max_force = -1.0;
  EXPECT_THROW(solver.setConfig(cfg), std::invalid_argument);
  ASSERT_TRUE(solver.solve(State{}, {ref}, control));
  EXPECT_NEAR(control.wrench.x(), 0.25, 1e-5);
}

